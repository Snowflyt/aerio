/**
 * Creates a transformed view of a {@linkcode Deferred} by mapping values read from `get` with `to` and values passed to `complete` with `from`.
 *
 * Pass the effect’s `map` operation as the first argument, for example `Deferred.imap(IO)`.
 *
 * **Example**
 *
 * ```typescript
 * const program = IO.gen(function* () {
 *   const deferred = yield* IO.deferred<number>();
 *   const text = deferred.pipe(Deferred.imap(IO)(String, Number));
 *   yield* text.pipe(Deferred.complete("42"));
 *   return yield* text.pipe(Deferred.get);
 * });
 *
 * IO.unsafeRunSync(program); // => "42"
 * ```
 */
export const imap: <F extends HKT<unknown, unknown>>(
  F: PickRaw<Covariant<F>, "map">,
) => Dual<
  <A, B>(
    self: Deferred<F, A>,
    to: (a: NoInfer<A>) => B,
    from: (b: NoInfer<B>) => A,
  ) => Deferred<F, B>,
  <A, B>(
    to: (a: NoInfer<A>) => B,
    from: (b: NoInfer<B>) => A,
  ) => (self: Deferred<F, A>) => Deferred<F, B>
> = <F extends HKT<unknown, unknown>>(
  F: Parameters<typeof core.deriveImap<F, PartialApply<DeferredHKT, [F]>>>[0],
) => dual(3, core.deriveImap<F, PartialApply<DeferredHKT, [F]>>(F, internal.DeferredProto));

/**
 * Gets the completed value of a {@linkcode Deferred}, waiting if it is still empty.
 *
 * This operation may be cancelled.
 *
 * **Example**
 *
 * ```typescript
 * const program = IO.gen(function* () {
 *   const deferred = yield* IO.deferred<number>();
 *   yield* deferred.pipe(Deferred.complete(42));
 *   return yield* deferred.pipe(Deferred.get);
 * });
 *
 * IO.unsafeRunSync(program); // => 42
 * ```
 */
export const get: <F extends HKT<unknown, unknown>, A>(self: Deferred<F, A>) => Call1<F, A> =
  /* @__PURE__ */ core.deriveGet();

/**
 * Completes a {@linkcode Deferred} with the given value if it is **empty**, and notifies all readers waiting on `get`.
 *
 * Returns `true` if the {@linkcode Deferred} was completed, and `false` if it was already completed.
 *
 * **Example**
 *
 * ```typescript
 * const program = IO.gen(function* () {
 *   const deferred = yield* IO.deferred<number>();
 *   const first = yield* deferred.pipe(Deferred.complete(1));
 *   const second = yield* deferred.pipe(Deferred.complete(2));
 *   const value = yield* deferred.pipe(Deferred.get);
 *   return [first, second, value] as const;
 * });
 *
 * IO.unsafeRunSync(program); // => [true, false, 1]
 * ```
 */
export const complete: Dual<
  <F extends HKT<unknown, unknown>, A>(self: Deferred<F, A>, a: A) => Call1<F, boolean>,
  <A>(a: A) => <F extends HKT<unknown, unknown>>(self: Deferred<F, A>) => Call1<F, boolean>
> = /* @__PURE__ */ dual(2, /* @__PURE__ */ core.deriveComplete());
